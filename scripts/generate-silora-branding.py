#!/usr/bin/env python3
"""Render the Silora artwork. Requires rsvg-convert, Pillow, and FFmpeg/libx264.

The wordmark contains outlined DejaVu Sans Bold lettering; no font install is needed.
Run from any directory with: python3 scripts/generate-silora-branding.py
"""

from io import BytesIO
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory
import xml.etree.ElementTree as ET

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BACKGROUND = "#25252D"
SPLASH_DURATION = "1.6"


def generate_tv_wordmark():
    """Keep TV's vector drawable in sync with the existing Silora SVG artwork."""
    svg = "{http://www.w3.org/2000/svg}"
    android = "http://schemas.android.com/apk/res/android"
    aapt = "http://schemas.android.com/aapt"
    ET.register_namespace("android", android)
    ET.register_namespace("aapt", aapt)

    def element(parent, tag, **attributes):
        return ET.SubElement(parent, tag, {
            f"{{{android}}}{key}": str(value) for key, value in attributes.items()
        })

    def translated_group(parent, source):
        # Both checked-in SVGs use translation-only groups/letter paths.
        transform = source.get("transform", "translate(0 0)")
        if not transform.startswith("translate(") or not transform.endswith(")"):
            raise ValueError(f"Unsupported artwork transform: {transform}")
        x, y = transform[10:-1].replace(",", " ").split()
        return element(parent, "group", translateX=x, translateY=y)

    vector = ET.Element("vector", {
        f"{{{android}}}width": "120dp", f"{{{android}}}height": "40dp",
        f"{{{android}}}viewportWidth": "1200", f"{{{android}}}viewportHeight": "400",
    })
    mark = ET.parse(ROOT / "branding/silora-mark.svg").getroot()
    # The wordmark's 400px image embeds the mark's 512px canvas.
    scaled = element(vector, "group", scaleX=400 / 512, scaleY=400 / 512)
    mark_group = mark.find(f"{svg}g")
    translated = translated_group(scaled, mark_group)
    gradient_source = mark.find(f"{svg}defs/{svg}linearGradient")
    for source in mark_group.findall(f"{svg}path"):
        fill = source.get("fill")
        path = element(translated, "path", pathData=source.attrib["d"])
        if fill == f"url(#{gradient_source.attrib['id']})":
            attr = ET.SubElement(path, f"{{{aapt}}}attr", name="android:fillColor")
            gradient = element(attr, "gradient", type="linear",
                               startX=gradient_source.attrib["x1"], startY=gradient_source.attrib["y1"],
                               endX=gradient_source.attrib["x2"], endY=gradient_source.attrib["y2"])
            for stop in gradient_source.findall(f"{svg}stop"):
                element(gradient, "item", color=stop.attrib["stop-color"], offset=stop.get("offset", "0"))
        else:
            path.set(f"{{{android}}}fillColor", fill)

    lettering = ET.parse(ROOT / "branding/silora-wordmark.svg").getroot().find(f"{svg}g")
    for source in lettering.findall(f"{svg}path"):
        element(translated_group(vector, source), "path",
                fillColor=lettering.attrib["fill"], pathData=source.attrib["d"])
    ET.indent(vector, space="    ")
    path = ROOT / "androidTvApp/src/androidMain/res/drawable/silo_wordmark.xml"
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                    '<!-- Silora artwork from branding/silora-{mark,wordmark}.svg.\n'
                    '     Generated by scripts/generate-silora-branding.py. -->\n'
                    + ET.tostring(vector, encoding="unicode") + "\n")


def render(name, width, height):
    return Image.open(BytesIO(subprocess.check_output([
        "rsvg-convert", "--width", str(width), "--height", str(height),
        str(ROOT / "branding" / name),
    ]))).convert("RGBA")


def generate_splash():
    # Keep the existing decoder tiers: 720p30 AVC 3.1 for weaker TV boxes,
    # and 1080p60 AVC 4.2 for devices that advertise support for it.
    raw = ROOT / "android-shared/src/androidMain/res/raw"
    with TemporaryDirectory(prefix="silora-splash-") as directory:
        wordmark_path = Path(directory) / "wordmark.png"
        for name, width, height, frame_rate, level in (
            ("startup_splash", 1280, 720, 30, "3.1"),
            ("startup_splash_hd", 1920, 1080, 60, "4.2"),
        ):
            wordmark_width = width * 9 // 10
            wordmark = render("silora-wordmark.svg", wordmark_width, wordmark_width // 3)
            # Composite transparency before encoding so the video and app
            # background share the same pure black.
            frame = Image.new("RGB", (width, height), "black")
            frame.paste(wordmark, ((width - wordmark.width) // 2,
                                  (height - wordmark.height) // 2), wordmark)
            frame.save(wordmark_path)
            subprocess.run([
                "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                "-loop", "1", "-framerate", str(frame_rate), "-i", str(wordmark_path),
                "-vf", "fade=t=in:st=0:d=0.25,fade=t=out:st=1.3:d=0.25,format=yuv420p",
                "-t", SPLASH_DURATION, "-an", "-c:v", "libx264",
                "-profile:v", "high", "-level:v", level, "-crf", "18",
                "-preset", "medium", "-threads", "2", "-movflags", "+faststart",
                "-map_metadata", "-1", "-metadata", "title=Silora startup splash",
                str(raw / f"{name}.mp4"),
            ], check=True)


def generate():
    foreground = render("silora-mark.svg", 512, 512)
    icon = Image.new("RGB", (512, 512), BACKGROUND)
    icon.paste(foreground, (0, 0), foreground)
    icon.save(ROOT / "assets/icon.png", optimize=True)
    wordmark = render("silora-wordmark.svg", 1200, 400)
    banner_wordmark = render("silora-wordmark.svg", 170, 57)
    banner = Image.new("RGB", (320, 180), BACKGROUND)
    banner.paste(banner_wordmark, (75, 61), banner_wordmark)
    for module in ("androidApp", "androidTvApp"):
        res = ROOT / module / "src/androidMain/res"
        icon.save(res / "mipmap-nodpi/ic_launcher.png", optimize=True)
        foreground.save(res / "mipmap-nodpi/ic_launcher_foreground.png", optimize=True)
        if module == "androidApp":
            wordmark.save(res / "drawable/silo_wordmark.png", optimize=True)
        if module == "androidTvApp":
            foreground.save(res / "drawable/silo_mark.png", optimize=True)
            banner.save(res / "drawable/tv_banner.png", optimize=True)
    generate_tv_wordmark()
    generate_splash()


if __name__ == "__main__":
    generate()
